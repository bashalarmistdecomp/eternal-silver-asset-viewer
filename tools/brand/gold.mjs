/** a letter as the logo's glyphs are: its mask, and its advance (the width of its body) */
export function letter(ch) {
  const rows = ROWS[ch];
  if (!rows) throw new Error(`the gold capitals have no ${JSON.stringify(ch)}`);
  const m = new Mask(rows[0].length, rows.length);
  rows.forEach((row, y) => [...row].forEach((c, x) => c === "#" && m.set(x, y)));
  return { m, adv: rows[0].length };
}

/** a line of words: [glyph, space before it], `track` pixels between letters and `word` between words */
export function words(text, { track = 3, word = 7 } = {}) {
  const out = [];
  for (const [i, w] of text.split(" ").entries())
    for (const [j, ch] of [...w].entries()) out.push([letter(ch), j > 0 ? track : i > 0 ? word : 0]);
  return out;
}
